/** Centralized instant language toggle helper */
export async function toggleLang(): Promise<Lang> {
  const current = langStore.get();
  const next: Lang = current === "id" ? "jp" : "id";
  if (next === "jp") {
    await ensureJpLoaded();
  }
  langStore.set(next);
  return next;
}