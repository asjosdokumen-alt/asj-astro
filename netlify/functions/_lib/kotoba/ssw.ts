/**
 * _lib/kotoba/ssw.ts — bank kosakata kerja untuk 16 bidang 特定技能 (SSW),
 * dipakai `/kotoba` sebagai modul latihan per bidang.
 *
 * KENAPA TERPISAH DARI `bank.ts`
 * -----------------------------
 * Dua dataset dengan umur dan aturan berbeda. `bank.ts` adalah kosakata BUKU
 * (Minna no Nihongo, bab 1–50) yang penempatan babnya terikat silabus; berkas
 * ini adalah kosakata LAPANGAN yang terikat bidang kerja. Menyatukannya berarti
 * setiap kali satu bidang ditambah, sebaran bab di `bank.ts` ikut berubah —
 * dan sebaliknya.
 *
 * LIMA KATEGORI, BUKAN SATU DAFTAR PANJANG
 * ---------------------------------------
 * Sejak 2026-10-31 tiap bidang dipecah lima kategori. Alasannya bukan kerapian:
 * daftar 60 kata tanpa struktur tidak bisa dipakai belajar, sementara ujian
 * 技能測定試験 menanyakan hal yang berbeda-beda — alat, urutan kerja,
 * keselamatan, mutu, dan dokumen/komunikasi. Dengan kategori, siswa bisa
 * men-drill "keselamatan" saja sebelum tes, dan kuisnya tetap satu mesin.
 *
 *   alat   — alat, bahan, mesin, perlengkapan
 *   kerja  — tindakan kerja (bentuk ます, siap dipakai di kalimat)
 *   aman   — keselamatan, higiene, bahaya, APD, tanggap darurat
 *   mutu   — mutu, pengukuran, standar, catatan hasil kerja
 *   kantor — dokumen, instruksi, laporan, serah terima shift
 *
 * ASAL DATA — dan batasnya
 * ------------------------
 * Daftar bidangnya mengikuti 16 bidang yang dibuka Jepang untuk 特定技能
 * (出入国在留管理庁): 介護, ビルクリーニング, 素形材・産業機械・電気電子情報
 * 関連製造業, 建設, 造船・舶用工業, 自動車整備, 航空, 宿泊, 農業, 漁業,
 * 飲食料品製造業, 外食業, 自動車運送業, 鉄道, 林業, 木材産業.
 *
 * Kosakatanya disusun dari istilah yang benar-benar dipakai di lapangan dan
 * dari cakupan yang biasa diujikan (peralatan, prosedur, keselamatan, mutu,
 * dokumen) — BUKAN salinan kisi-kisi resmi 技能測定試験 atau buku teks, karena
 * tidak ada dokumen itu di tangan. Artinya: modul ini melatih MENGENALI alat,
 * instruksi, dan istilah kerja; ia bukan jaminan cakupan ujian. Kalau nanti
 * kisi-kisi resmi per bidang didapat, berkas inilah yang pertama disesuaikan.
 *
 * Ujian 特定技能1号評価試験 menguji 学科 (pengetahuan) dan 実技 (praktik), dan
 * soalnya ditulis dalam bahasa Jepang. Karena itu kata kerja di sini sengaja
 * dibiarkan dalam bentuk ます — bentuk yang muncul di instruksi kerja
 * ("〜してください") — bukan bentuk kamus.
 *
 * CARA MEMERIKSA
 * --------------
 * Sama seperti `bank.ts`: kolom `h` (kana) diubah ke romaji oleh konverter di
 * `e2e/kotoba-bank.test.ts` lalu dibandingkan dengan kolom `r`. Tes itu juga
 * menolak kunci `k|h` ganda DI DALAM satu bidang — kunci itulah yang dipakai
 * menyimpan progres hafalan siswa, jadi satu duplikat berarti dua kata berbagi
 * satu riwayat — dan menuntut tiap kategori terisi di tiap bidang.
 *
 * BENTUK
 * ------
 * Tuple, alasannya sama dengan `bank.ts`: nama kunci berulang tidak ikut
 * di-bundle. Urutannya dikunci `KolomSsw` — jangan diubah tanpa `keKata()`.
 *
 * `b: 0` pada hasil konversi BUKAN bab buku. Ia ada supaya bentuk katanya sama
 * persis dengan `Kotoba` di `bank.ts`, sehingga `KotobaGame` bisa memakai satu
 * mesin kuis untuk dua sumber. Nilai 0 juga membuat pengelompokan pengecoh
 * "bab sama" otomatis berarti "bidang yang sama".
 */

/** Jenis kata — nilainya sama dengan `JenisKata` di `bank.ts`. */
export type JenisKataSsw = 'verb' | 'adj' | 'noun' | 'other';

/**
 * Kategori kerja. Nilainya dipakai sebagai kunci filter di klien DAN sebagai
 * kunci i18n (`kotoba.cat_<id>`), jadi menambah kategori berarti menambah
 * label di dua kamus — bukan sekadar menambah string di sini.
 */
export type KategoriSsw = 'alat' | 'kerja' | 'aman' | 'mutu' | 'kantor';

/** Satu kata bidang dalam bentuk yang dikirim ke klien. */
export interface KotobaSsw {
  /** Selalu 0: penanda "bukan bab buku". Lihat catatan di atas. */
  b: 0;
  cat: KategoriSsw;
  pos: JenisKataSsw;
  /** Tulisan kanji/katakana seperti tertulis di lapangan. */
  k: string;
  /** Cara baca hiragana. */
  h: string;
  /** Romaji — dipakai mode ketik dan pencarian. */
  r: string;
  /** Arti Bahasa Indonesia. */
  id: string;
}

/** Satu bidang kerja. */
export interface BidangSsw {
  /** Id stabil: dipakai sebagai kunci progres di localStorage. Jangan diganti. */
  id: string;
  /** Nama Indonesia. */
  nama: string;
  /** Nama resmi Jepang. */
  namaJp: string;
  /** Satu kalimat: apa yang dikerjakan di lapangan. */
  ringkas: string;
  kata: readonly KotobaSsw[];
}

/** Urutan kolom tuple: [kategori, jenis, kanji, hiragana, romaji, arti]. */
type KolomSsw = readonly [KategoriSsw, JenisKataSsw, string, string, string, string];

function keKata(t: KolomSsw): KotobaSsw {
  return { b: 0, cat: t[0], pos: t[1], k: t[2], h: t[3], r: t[4], id: t[5] };
}

