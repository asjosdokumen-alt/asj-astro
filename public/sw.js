/* ASJ Portal v2 — Service Worker
 *
 * Strategy
 * --------
 * - Precache: the app shell + every hashed build asset (written at build time
 *   by scripts/build-sw-manifest.mjs). Makes the app genuinely installable and
 *   usable offline after the first visit.
 * - Navigation: network-first (online = fresh, offline = cached page).
 * - Static assets: stale-while-revalidate, so we never block on the network.
 * - API calls: never cached, always network.
 * - install → skipWaiting(); activate → drop old caches + claim tabs.
 *
 * IMPORTANT: the `PRECACHE` block below is machine-generated. Do not hand-edit
 * the list — edit scripts/build-sw-manifest.mjs instead. `public/sw.js` keeps
 * the block empty so `astro dev` (no build script) still works.
 */

const VERSION = 'asj-astro-dev';

// The array body between the markers is machine-generated by
// scripts/build-sw-manifest.mjs. Keep the declaration line outside the markers
// so repeated builds stay parseable.
const PRECACHE = [
// PRECACHE_START
  '/',
  '/index.html',
  '/candidate/',
  '/admin/',
  '/public/',
// PRECACHE_END
];

// ─── INSTALL: activate immediately + precache the shell ──────────────────────
self.addEventListener('install', (e) => {
  self.skipWaiting();
  e.waitUntil(
    (async () => {
      const cache = await caches.open(VERSION);
      // Tolerate individual failures: a single 404 must not abort the install.
      await Promise.all(PRECACHE.map((url) => cache.add(url).catch(() => {})));
    })(),
  );
});

// ─── ACTIVATE: drop old caches + claim open tabs ─────────────────────────────
self.addEventListener('activate', (e) => {
  e.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k)));
      await self.clients.claim();
      const clients = await self.clients.matchAll({ type: 'window' });
      clients.forEach((c) => c.postMessage({ type: 'ASJ_FORCE_RELOAD' }));
    })(),
  );
});

// ─── MESSAGE: page-initiated skipWaiting ─────────────────────────────────────
self.addEventListener('message', (e) => {
  if (e.data?.type === 'SKIP_WAITING') self.skipWaiting();
});

// ─── PUSH: tampilkan notifikasi FCM saat aplikasi TIDAK di depan ─────────────
//
// KENAPA WAJIB ADA — 2026-10-13. Payload kita DATA-ONLY
// (`buildPushPayload()` mengirim `message.data`, tanpa blok `notification`).
// Untuk pesan data-only, FCM TIDAK menampilkan apa pun sendiri: browser
// menyerahkan PushEvent ke service worker, dan kalau tidak ada listener
// `push` yang memanggil `showNotification()`, notifikasinya HILANG tanpa
// jejak — persis keluhan "tidak ada notif".
//
// Biasanya SDK Firebase memasang handler ini sendiri di
// `firebase-messaging-sw.js`, TAPI `src/lib/fcm.ts` mendaftarkan token dengan
// `serviceWorkerRegistration` EKSPLISIT yang menunjuk ke berkas ini, sehingga
// penanganan bawaan SDK dilewati. Jadi handler-nya harus ada di sini.
//
// `event.data.json()` = isi `message.data` dari `buildPushPayload()`
// (`title`, `body`, `url`). Payload non-JSON (mis. pesan kontrol) diabaikan
// dengan aman, dan `waitUntil` menahan SW tetap hidup sampai notifikasi
// benar-benar tampil.
self.addEventListener('push', (e) => {
  let payload = {};
  try {
    payload = e.data ? e.data.json() : {};
  } catch {
    // Bukan JSON (payload uji atau pesan kontrol) — jangan melempar di dalam
    // event handler, karena akan membatalkan seluruh penanganan push.
    payload = {};
  }

  // Data-only: fieldnya di akar payload. `notification` juga dibaca supaya
  // pesan yang (suatu saat) memakai blok itu tetap tampil.
  const notif = payload.notification || {};
  const data = payload.data || payload;
  const title = data.title || notif.title || 'PT Amanah Sakura Japan';
  const body = data.body || notif.body || '';
  const url = data.url || '/';

  e.waitUntil(
    self.registration.showNotification(title, {
      body: body,
      icon: '/icons/icon-192.png',
      badge: '/icons/favicon-32.png',
      // Ikon mana pun yang ditunjuk HARUS ada dan tembus pandang, kalau tidak
      // latar gelapnya terbaca sebagai kotak hitam di notifikasi.
      data: { url: url },
      tag: 'asj-notif',
      renotify: true,
    }),
  );
});

// ─── NOTIFICATIONCLICK: buka/fokus tab tujuan ────────────────────────────────
self.addEventListener('notificationclick', (e) => {
  e.notification.close();
  const target = (e.notification.data && e.notification.data.url) || '/';

  e.waitUntil(
    (async () => {
      const url = new URL(target, self.location.origin).href;
      const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      // Sudah ada tab aplikasi? fokuskan dan arahkan ke tujuannya, jangan
      // membuka tab baru — perilaku yang sama dengan notifikasi native.
      for (const c of clients) {
        if (c.url.startsWith(self.location.origin)) {
          await c.focus();
          if ('navigate' in c) await c.navigate(url).catch(() => {});
          return;
        }
      }
      await self.clients.openWindow(url);
    })(),
  );
});

// ─── FETCH: route by request type ────────────────────────────────────────────
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);

  // Never touch other origins (Supabase, CDNs, fonts.googleapis, …).
  if (url.origin !== self.location.origin) return;

  // Never cache API traffic — it is authenticated and must be live.
  if (url.pathname.startsWith('/.netlify/') || url.pathname.startsWith('/api/')) return;

  // Navigation + HTML → network-first, fall back to cache, then to the shell.
  if (req.mode === 'navigate' || url.pathname.endsWith('.html') || url.pathname.endsWith('/')) {
    e.respondWith(
      fetch(req.url, { cache: 'no-cache' })
        .then((res) => {
          // A response that FOLLOWED a redirect must never be handed back to a
          // navigation request: Chrome rejects it and fails the whole navigation
          // with `net::ERR_FAILED`, before any of our HTML is parsed.
          //
          // This was a live outage, not a hypothetical. Netlify 301s every bare
          // directory route to its trailing-slash form (`/admin` -> `/admin/`,
          // verified against production 2026-09-13), and the app links to the
          // BARE form. So with this worker in control, `/admin`, `/candidate`,
          // `/public` and `/apply` all died while their trailing-slash twins
          // worked — which is what made it look like "redirects are broken".
          //
          // Rebuilding the response from its body clears the `redirected` flag
          // while preserving status and headers, so the navigation succeeds and
          // still gets the real page.
          const out = res.redirected
            ? new Response(res.body, {
                status: res.status,
                statusText: res.statusText,
                headers: res.headers,
              })
            : res;
          if (out.status === 200) {
            const copy = out.clone();
            // `.catch` is not decoration: `cache.put` rejects for responses it
            // will not store (e.g. a redirected one), and an unhandled rejection
            // inside a fetch handler is invisible in production.
            caches.open(VERSION).then((c) => c.put(url.pathname, copy)).catch(() => {});
          }
          return out;
        })
        .catch(async () => {
          const cache = await caches.open(VERSION);
          return (
            (await cache.match(url.pathname)) ||
            (await cache.match('/index.html')) ||
            new Response(
              '<!doctype html><meta charset="utf-8"><title>Offline</title>' +
                '<body style="font-family:system-ui;padding:2rem">' +
                '<h1>Anda sedang offline</h1>' +
                '<p>Halaman ini belum pernah dibuka, jadi belum tersimpan di perangkat.</p>' +
                '</body>',
              { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' } },
            )
          );
        }),
    );
    return;
  }

  // Static assets → stale-while-revalidate (cache hit wins, refresh behind it).
  e.respondWith(
    caches.match(req).then((hit) => {
      const network = fetch(req)
        .then((res) => {
          if (res?.status === 200) {
            const copy = res.clone();
            caches.open(VERSION).then((c) => c.put(req, copy)).catch(() => {});
          }
          return res;
        })
        // Never resolve to `undefined`: `respondWith(undefined)` is a failed
        // request, and that is exactly the case where a readable error matters
        // most. A 504 keeps the failure legible in devtools instead of a bare
        // net::ERR_FAILED.
        .catch(() => hit || new Response('', { status: 504, statusText: 'Gateway Timeout' }));
      return hit || network;
    }),
  );
});
